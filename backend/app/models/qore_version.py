from datetime import datetime

from sqlalchemy import Boolean, DateTime, String, Text
from sqlalchemy.orm import Mapped, mapped_column

from app.database import Base


class QoreVersion(Base):
    """One uploaded QORE .so build. QORE's own API exposes no version string
    (checked: nothing in engines/qore/qore_opt_py.pyi, generated by stubgen
    itself, which would show it if it existed) — `label` is an admin-typed
    free-text identifier instead of a real semantic version.
    """

    __tablename__ = "qore_versions"

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    label: Mapped[str] = mapped_column(String, nullable=False)
    so_path: Mapped[str] = mapped_column(String, nullable=False)
    active: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    smoke_test_ok: Mapped[bool] = mapped_column(Boolean, nullable=False)
    smoke_test_output: Mapped[str | None] = mapped_column(Text, nullable=True)
    uploaded_by: Mapped[str | None] = mapped_column(String, nullable=True)
    uploaded_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
